#!/usr/bin/env python3
"""Maps desktop GL names to gl4es's functions, for the iOS build.

gl4es defines each GL function as gl4es_<name>; on ELF systems it also exports
the plain name as an alias, but Mach-O has no aliases, so on Apple platforms
only the gl4es_ names exist. This writes a header of
    #define glBindFramebufferEXT gl4es_glBindFramebuffer
lines from gl4es's AliasExport declarations. gl_host.h includes it after
gl4es's GL/gl.h, whose own renaming (gl_mangle.h) maps every name to
gl4es_<name>, including suffixed names gl4es does not define on Apple; these
lines replace those.

usage: gl4es_names.py GL4ES_SOURCE_DIR OUT_HEADER
"""
import os
import re
import sys

# AliasExport(RET,NAME,X,DEF) and its variants: the exported name is NAME + X,
# the implementation gl4es_ + NAME (or the INM argument of AliasExport_A).
CALL = re.compile(r'\b(AliasExport(?:_A|_D|_D_1|_M|_V|_1)?|_AliasExport_)\(')


def args(text, start):
    """The macro's arguments from just after its '(' (nested parentheses kept whole)."""
    depth, cur, out = 0, '', []
    for ch in text[start:]:
        if ch == '(':
            depth += 1
        elif ch == ')':
            if depth == 0:
                out.append(cur.strip())
                return out
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    return out


def main():
    src, out = sys.argv[1], sys.argv[2]
    names = {}
    for root, _, files in os.walk(os.path.join(src, 'src')):
        for f in files:
            if not f.endswith('.c'):
                continue
            text = open(os.path.join(root, f), encoding='utf-8', errors='replace').read()
            for m in CALL.finditer(text):
                a = args(text, m.end())
                kind = m.group(1)
                if kind == '_AliasExport_' and len(a) >= 4:
                    exported, impl = a[1], a[3]
                elif kind == 'AliasExport_V' and len(a) >= 2:
                    exported, impl = a[1], a[1]
                elif kind == 'AliasExport_A' and len(a) >= 5:
                    exported, impl = a[1] + a[2], a[4]
                elif len(a) >= 3:
                    exported, impl = a[1] + a[2], a[1]
                else:
                    continue
                if re.fullmatch(r'gl[A-Za-z0-9_]+', exported) and re.fullmatch(r'[A-Za-z0-9_]+', impl):
                    names[exported] = 'gl4es_' + impl
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as o:
        o.write('// Generated by tools/gl4es_names.py: GL names to gl4es\'s functions (iOS)\n#pragma once\n')
        for k in sorted(names):
            o.write('#undef %s\n#define %s %s\n' % (k, k, names[k]))
    print('gl4es_names: %d names' % len(names))


if __name__ == '__main__':
    main()
