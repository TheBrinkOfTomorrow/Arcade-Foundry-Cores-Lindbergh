#!/usr/bin/env python3
"""Generate the guest -> host OpenGL bridge from the Khronos gl.xml registry.

Each wrapper reads the i386 stack arguments of one GL command, converts guest
pointers into host pointers, and calls the host GL through a pointer looked up
at run time. Commands with no wrapper here are reported as missing to
glXGetProcAddress, so the game sees them as unavailable.

Usage: glgen.py gl.xml names.txt out.c
names.txt: extra command names to include beyond GL 1.0-2.1 (one per line).
"""
import re
import sys
import xml.etree.ElementTree as ET

SPECIAL = {
    # hand-written in hle_gfx.c
    'glGetString', 'glGetStringi', 'glMapBuffer', 'glMapBufferARB', 'glUnmapBuffer', 'glUnmapBufferARB',
    'glBindBuffer', 'glBindBufferARB', 'glShaderSource', 'glShaderSourceARB', 'glGetPointerv',
    'glGetPointervEXT', 'glMultiDrawElements', 'glMultiDrawElementsEXT', 'glGetBufferPointerv',
    'glGetBufferPointervARB', 'glGetVertexAttribPointerv', 'glGetVertexAttribPointervARB',
    'glGetVertexAttribPointervNV', 'glFeedbackBuffer', 'glSelectBuffer', 'glMultiDrawArrays', 'glMultiDrawArraysEXT',
    'glCompileShader', 'glCompileShaderARB', 'glLinkProgram', 'glLinkProgramARB',
    'glAttachShader', 'glAttachObjectARB',
}
BAD_TYPES = ('GLDEBUGPROC', 'GLsync', 'GLeglImageOES', 'GLeglClientBufferEXT', 'GLVULKANPROCNV', 'struct _cl', 'GLhalfNV *', 'GLvdpauSurfaceNV')


def ctext(e):
    return ''.join(e.itertext()).strip()


def main():
    reg = ET.parse(sys.argv[1]).getroot()
    extra = set(l.strip() for l in open(sys.argv[2]) if l.strip())
    want = set()
    for f in reg.findall('feature'):
        if f.get('api') != 'gl':
            continue
        num = float(f.get('number'))
        if num <= 2.1:
            for r in f.findall('require'):
                for c in r.findall('command'):
                    want.add(c.get('name'))
    want |= extra
    cmds = {}
    for c in reg.find('commands').findall('command'):
        proto = c.find('proto')
        name = proto.find('name').text
        if name not in want or name in SPECIAL:
            continue
        rtype = (proto.text or '') + ''.join((ptp.text or '') + (ptp.tail or '') for ptp in proto.findall('ptype'))
        rtype = ctext(proto)[:-len(name)].strip()
        params = []
        ok = True
        for p in c.findall('param'):
            full = ctext(p)
            pname = p.find('name').text
            ptype = full[:full.rfind(pname)].strip()
            if any(b in full for b in BAD_TYPES):
                ok = False
            params.append((ptype, pname))
        if ok:
            cmds[name] = (rtype, params)
    out = ['// Generated by tools/glgen.py from the Khronos gl.xml registry. Do not edit.',
           '#include "hle.h"', '#include "gl_host.h"', '']
    table = []
    for name in sorted(cmds):
        rtype, params = cmds[name]
        conv = []
        args = []
        slot = 0
        ptr_params = [i for i, (t, n) in enumerate(params) if '*' in t]
        for i, (t, n) in enumerate(params):
            base = t.replace('const', '').replace('*', '').strip()
            if '*' in t:
                # array pointers may be offsets into a bound buffer object
                if ('Pointer' in name and i == ptr_params[-1]) or (name.startswith('glVertexAttribPointer') and i == ptr_params[-1]):
                    conv.append('%s a%d = (%s)gl_array_ptr(ARG(%d));' % (t, i, t, slot))
                elif name in ('glDrawElements', 'glDrawRangeElements', 'glDrawRangeElementsEXT') and i == ptr_params[-1]:
                    conv.append('%s a%d = (%s)gl_element_ptr(ARG(%d));' % (t, i, t, slot))
                else:
                    conv.append('%s a%d = (%s)(ARG(%d) ? (void *)G(ARG(%d)) : NULL);' % (t, i, t, slot, slot))
                slot += 1
            elif base in ('GLdouble', 'GLclampd'):
                conv.append('%s a%d = ARGD(%d);' % (t, i, slot))
                slot += 2
            elif base in ('GLfloat', 'GLclampf'):
                conv.append('%s a%d = ARGF(%d);' % (t, i, slot))
                slot += 1
            elif base in ('GLint64', 'GLuint64', 'GLint64EXT', 'GLuint64EXT'):
                conv.append('%s a%d = (%s)ARGQ(%d);' % (t, i, t, slot))
                slot += 2
            elif base in ('GLsizeiptr', 'GLintptr', 'GLsizeiptrARB', 'GLintptrARB'):
                conv.append('%s a%d = (%s)(int32_t)ARG(%d);' % (t, i, t, slot))
                slot += 1
            elif base == 'GLhandleARB':
                conv.append('%s a%d = (%s)(uintptr_t)ARG(%d);' % (t, i, t, slot))
                slot += 1
            else:
                conv.append('%s a%d = (%s)ARG(%d);' % (t, i, t, slot))
                slot += 1
            args.append('a%d' % i)
        proto_params = ', '.join(t for t, n in params) or 'void'
        call = 'p(%s)' % ', '.join(args)
        if rtype == 'void':
            ret = call + ';'
        elif '*' in rtype:
            continue
        elif rtype == 'GLhandleARB':
            ret = 'RET((uint32_t)(uintptr_t)%s);' % call
        else:
            ret = 'RET((uint32_t)%s);' % call
        out.append('static void w_%s(CPU *c)\n{\n    typedef %s (APIENTRY *fn)(%s);\n    static fn p;\n    if (!gl_open) RET(0);   // before the window: no context (the OutRun 2 SP test menu asks for errors)\n    if (!p) p = (fn)gl_host_proc("%s");\n    if (!p) RET(0);   // not on the host\n    %s\n    if (gl_trace) gl_trace_call("%s", c);\n    %s\n}\n' % (
            name, rtype, proto_params, name, '\n    '.join(conv), name, ret))
        table.append(name)
    out.append('const hle_entry gl_gen_table[] = {')
    for n in table:
        out.append('    {"%s", w_%s},' % (n, n))
    out.append('    {NULL, NULL},\n};')
    open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
    print('%d GL wrappers' % len(table))


if __name__ == '__main__':
    main()
