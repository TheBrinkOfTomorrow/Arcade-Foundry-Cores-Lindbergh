#!/usr/bin/env python3
"""Render runtime/boot_font.h: a 10x20 console font for the test-menu stand-in.

The cabinet's test menu loads its font from the Lindbergh system disk
(/usr/lib/boot/LucidaConsole_12.*), which is not part of the game data. The
runtime builds a replacement from these glyphs, rendered from DejaVu Sans Mono
with ImageMagick. Glyphs are 4-bit coverage, two pixels per byte, high nibble first.
"""
import subprocess, sys

W, H, FIRST, LAST = 10, 20, 32, 126
FONT = sys.argv[1] if len(sys.argv) > 1 else 'DejaVu-Sans-Mono'

out = ['// Generated by tools/mkfont.py from %s (Bitstream Vera / DejaVu licence). Do not edit.' % FONT,
       '#define BOOT_FONT_W %d' % W, '#define BOOT_FONT_H %d' % H,
       '#define BOOT_FONT_FIRST %d' % FIRST, '#define BOOT_FONT_LAST %d' % LAST,
       'static const unsigned char boot_font[%d][%d] = {' % (LAST - FIRST + 1, W * H // 2)]
for ch in range(FIRST, LAST + 1):
    text = chr(ch)
    if text == '\\': text = '\\\\'
    px = subprocess.run(['convert', '-size', '%dx%d' % (W, H), 'xc:black', '-font', FONT, '-pointsize', '16',
                         '-fill', 'white', '-annotate', '+0+15', text, '-depth', '8', 'gray:-'],
                        check=True, capture_output=True).stdout
    assert len(px) == W * H
    nib = [p >> 4 for p in px]
    packed = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    out.append('    {' + ','.join('0x%02x' % b for b in packed) + '}, // %r' % chr(ch))
out.append('};')
print('\n'.join(out))
